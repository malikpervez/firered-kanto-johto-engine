#!/usr/bin/env python3
"""Keep only the Hoenn map scripts the FireRed Kanto + Johto game still uses.

The FireRed build skips the Hoenn map scripts (data/event_scripts.s, `#ifndef FIRERED`). Some of their labels are still
used by shared scripts, kept maps and native code (Game Corner slot machines, lab bookshelves, ferry helpers, the
player's house texts...). This writes:

* engine/data/scripts/hoenn_kept.inc: those labels' original blocks, plus every Hoenn block they reach (goto, call,
  msgbox, movement...) and blocks they fall through into, in their original order;
* engine/data/scripts/hoenn_stubs.inc: a harmless definition for each label only used by removed Hoenn and Battle
  Frontier features (`end` for scripts, an empty string for texts, `step_end` for movements).

Input: a JSON file {"keep": [labels], "stub": [labels]} from the link errors of a build without the Hoenn scripts.
Rerun with the new link errors until the build links.
"""
import argparse
import json
import re
from pathlib import Path

LABEL = re.compile(r"^([A-Za-z_]\w*)::?\s*(?:@.*)?$")
IDENT = re.compile(r"\b[A-Za-z_]\w*\b")
TERMINATORS = re.compile(r"^\s*(end|return|goto\s+\w+|step_end|releaseall\s*$|waitstate|\.byte\s+0|\.2byte\s+0|"
                         r"\.4byte\s+0|\.string\s+\".*\$\"|mapscript_end)\b")


def hoenn_files(engine: Path) -> list[Path]:
    text = (engine / "data/event_scripts.s").read_text()
    start = text.index("@ Hoenn maps are not part of the FireRed Kanto + Johto game")
    block = text[start:text.index("#endif", start)]
    return [engine / m for m in re.findall(r'\.include "([^"]+)"', block)]


def blocks_of(path: Path) -> list[tuple[str, list[str]]]:
    out, cur, lines = [], None, []
    for ln in path.read_text(errors="replace").split("\n"):
        m = LABEL.match(ln)
        if m:
            if cur is not None or lines:
                out.append((cur, lines))
            cur, lines = m.group(1), [ln]
        else:
            lines.append(ln)
    out.append((cur, lines))
    return out


def ends(lines: list[str]) -> bool:
    body = [ln for ln in lines if ln.strip() and not ln.strip().startswith("@")]
    return bool(body) and bool(TERMINATORS.match(body[-1]))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--engine", type=Path, default=Path(__file__).resolve().parents[2] / "engine")
    ap.add_argument("missing", type=Path, help='JSON {"keep": [...], "stub": [...]}')
    a = ap.parse_args()
    eng = a.engine
    m = json.loads(a.missing.read_text())
    kept_file, stub_file = eng / "data/scripts/hoenn_kept.inc", eng / "data/scripts/hoenn_stubs.inc"
    # earlier rounds are kept: labels add up
    prev_keep = set(re.findall(r"^@ keep (\w+)$", kept_file.read_text(), re.M)) if kept_file.exists() else set()
    prev_stub = set(re.findall(r"^(\w+)::$", stub_file.read_text(), re.M)) if stub_file.exists() else set()
    want_keep = (prev_keep | set(m["keep"])) - set()
    want_stub = (prev_stub | set(m["stub"])) - want_keep

    files = hoenn_files(eng)
    blocks = {f: blocks_of(f) for f in files}
    where = {}
    for f, bl in blocks.items():
        for i, (lab, _) in enumerate(bl):
            if lab:
                where[lab] = (f, i)
    take = {f: set() for f in files}
    todo = [s for s in want_keep if s in where]
    seen = set()
    while todo:
        s = todo.pop()
        if s in seen:
            continue
        seen.add(s)
        f, i = where[s]
        while True:
            take[f].add(i)
            lab, lines = blocks[f][i]
            for tok in IDENT.findall("\n".join(ln.split("@")[0] for ln in lines[1:])):
                if tok in where and tok not in seen:
                    todo.append(tok)
            if ends(lines) or i + 1 >= len(blocks[f]):
                break
            i += 1  # falls through into the next label
            if blocks[f][i][0]:
                seen.add(blocks[f][i][0])
    kept_labels = {blocks[f][i][0] for f in files for i in take[f] if blocks[f][i][0]}
    out = ["@ Generated by project/scripts/prune_hoenn_scripts.py: Hoenn map script blocks the FireRed game still uses.",
           "@ Do not edit by hand; edit the Hoenn map's scripts.inc and rerun.", ""]
    out += [f"@ keep {s}" for s in sorted(want_keep)] + [""]
    for f in files:
        if not take[f]:
            continue
        out.append(f"@ from {f.relative_to(eng)}")
        # constants the file defines anywhere (.set lines, such as the Game Corner's prices), unless already taken
        taken = {id(ln) for i in take[f] for ln in blocks[f][i][1]}
        out.extend(ln for _, lines in blocks[f] for ln in lines
                   if re.match(r"\s*\.(set|equ|equiv)\s", ln) and id(ln) not in taken)
        for i in sorted(take[f]):
            out.extend(blocks[f][i][1])
        out.append("")
    kept_file.write_text("\n".join(out) + "\n")
    stubs = ["@ Generated by project/scripts/prune_hoenn_scripts.py: labels of removed Hoenn and Battle Frontier",
             "@ content that native code still names. They do nothing.", ""]
    for s in sorted(want_stub - kept_labels):
        if "_Text_" in s or s.startswith("gText_") or s.endswith("_Text"):
            stubs += [f"{s}::", '\t.string "$"', ""]
        elif "_Movement_" in s:
            stubs += [f"{s}::", "\tstep_end", ""]
        else:
            stubs += [f"{s}::", "\tend", ""]
    stub_file.write_text("\n".join(stubs) + "\n")
    missing_keep = sorted(s for s in want_keep if s not in where)
    print(f"kept {len(kept_labels)} labels from {sum(1 for f in files if take[f])} Hoenn files; "
          f"{len(want_stub - kept_labels)} stubs")
    if missing_keep:
        print("not defined in the Hoenn scripts (look elsewhere):", ", ".join(missing_keep[:40]))


if __name__ == "__main__":
    main()
